import copy

import fastgen.configs.methods.config_kd as config_kd_default
from fastgen.configs.data import DATA_ROOT_DIR, PairLoaderConfig
from fastgen.configs.net import CKPT_ROOT_DIR, EDM_CIFAR10_Config

""" Single-step KD on CIFAR-10 from the EDM cond-vp teacher.

Pairs are generated by `scripts/data_gen/generate_edm_kd_pairs.py` into `$DATA_ROOT_DIR/cifar10-edm-kd-pairs`.
The student is initialized from the teacher weights.
"""


def create_config():
    config = config_kd_default.create_config()

    config.model.net = EDM_CIFAR10_Config
    config.model.pretrained_model_path = f"{CKPT_ROOT_DIR}/cifar10/edm-cifar10-32x32-cond-vp.pth"
    config.model.input_shape = [3, 32, 32]
    config.model.student_sample_steps = 1
    config.model.net_optimizer.lr = 1e-4
    config.model.use_ema = False

    config.dataloader_train = copy.deepcopy(PairLoaderConfig)
    config.dataloader_train.datatags = [f"WDS:{DATA_ROOT_DIR}/cifar10-edm-kd-pairs"]
    config.dataloader_train.batch_size = 256

    config.trainer.max_iter = 4000
    config.trainer.logging_iter = 50
    config.trainer.save_ckpt_iter = 500
    config.trainer.validation_iter = 1000

    config.eval.num_samples = 10000

    config.log_config.wandb_mode = "disabled"
    config.log_config.group = "cifar10_kd"
    config.log_config.name = "kd_baseline"
    return config
